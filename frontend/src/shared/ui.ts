  '冷淡', '盯着', '无语', '小声嘀咕',
  // v3.51（D241）：从真实记录里数出来的（平和 71 次！调侃 10 / 嘟囔 5 / 小声 4 / 沮丧 2）
  '平和', '调侃', '嘟囔', '小声', '沮丧',
