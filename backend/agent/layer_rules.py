"""选层规则：四个 layer 分别什么时候用（**唯一来源**）。

两条写记忆的路径都引用这里，避免"两处说法不一样"：
  · 聊天时模型顺手记 → `context.HARD_RULE_BLOCK`
  · 停歇补漏提取     → `catchup_service.EXTRACTION_SYSTEM`

写法要求（重要）：**必须是能判断的是非题，不能是"重要/不太重要"这种形容词** ——
形容词模型就会乱分。所以规则是"从上往下问，命中就停"。
"""

LAYER_DECISION_RULES = """【怎么选 layer —— 从上往下判断，命中就停】
1. 用户**明确**让你记住的（"记住…"/"别忘了…"/"帮我记一下…"）→ `pinned`
2. 这条**过一年也依然成立**吗？（名字、生日、家人、工作、长期口味或习惯）
   → 是 → `permanent`
3. 这条**只是这阵子的状态**吗？（最近在学/在做的事、某个计划、某段经历、近况）
   → 是 → `long_term`
4. 只在这几天有意义、很快就没用（今天心情、刚才的临时安排）→ `short_term`
5. 拿不准 → `long_term`（默认值）

对照例子（照着分，别自由发挥）：
· "用户叫天海梦汐"         → permanent（名字是常量）
· "用户生日是 5 月 20 日"   → permanent（除非用户明确说"记住"，那就 pinned）
· "用户不吃香菜"           → permanent（长期口味，不会变）
· "用户最近在学 Rust"       → long_term（这阵子的状态）
· "用户在做 yumeFriend 项目" → long_term（这阵子的事）
· "用户下周要去日本出差"     → long_term（有期限的计划）
· "用户今天有点累"          → short_term（过两天就没意义）
· "记住我生日是 5 月 20 日"  → pinned（用户明确要求）"""


